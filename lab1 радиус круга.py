# Задаем константу Пи
PI = 3.141592

# Ввод данных 
R = float(input("Введите радиус круга (R): "))

# вычисления 
length = 2 * PI * R
area = PI * R ** 2

# Вывод данных с округлением до сотых
print("Результаты расчетов: ")
print("Длина окружности =", round(length, 2))
print("Площадь круга =", round(area, 2))